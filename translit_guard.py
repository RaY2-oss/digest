# -*- coding: utf-8 -*-
"""translit_guard.py — слово источника, переписанное кириллицей вместо перевода.

09.08.2026 в дайджест ушло «В Турции увеличен контэнджан стипендиальной
программы TENMAK», днём раньше — «контентжант». В турецком `kontenjan` это
«квота мест», обычное нарицательное слово; модель не перевела его, а записала
русскими буквами. Ошибка тихая: JSON валиден, текст русский, доля кириллицы в
норме, и все шесть прежних сторожей такой пункт пропускают.

Правило ушло в промпт, но правило промпта — договорённость, а не гарантия:
модель соблюдает его вероятностно, и на второй день соблюдать перестала. Здесь
измеряющая часть.

Как отличается транслитерация от законного заимствования. «Хакатон» и
«коворкинг» тоже пришли из чужого языка, но они уже русские слова — они
встречаются в русских текстах. `kontenjan` не встречается. Значит признак
такой: слова нет в русском вебе (wordfreq) И оно совпадает со словом
источника, набранным латиницей. Обе половины нужны: первая одна даёт 18%
брака на отгруженных дайджестах («межсекторального», «астронавтическом»,
«геопарк» — нормальные русские сложения, которых нет в частотных списках),
вторая одна ловила бы «университет» рядом с турецким `üniversite`.

Замер по 487 отгруженным пунктам: у 59 текст источника ещё лежит в базе, и
связка отметила ровно два — те самые. Ни одного ложного.

Морфология не нужна и не подключается. Проверять «есть ли такое слово в
русском» через pymorphy пробовали: словарь OpenCorpora не знает ни
«кибербезопасности», ни «цифровизации», ни «хакатона», а разбор через
угадывающие анализаторы одинаково уверенно принимает и «межсекторального», и
«контэнджан» — разделить по методу разбора не выходит.
"""
import difflib
import re
import unicodedata

from wordfreq import zipf_frequency

# Кириллица → латинский скелет: одна буква на звук. Точность здесь не нужна,
# нужна общая система координат для двух написаний одного слова.
_CYR = {"а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
        "ж": "j", "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m",
        "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
        "ф": "f", "х": "h", "ц": "c", "ч": "c", "ш": "s", "щ": "s", "ъ": "",
        "ы": "i", "ь": "", "э": "e", "ю": "u", "я": "a"}

# Пары букв, которыми один звук записывают по-разному: турецкое c и русское
# «дж», турецкое ş и русское «ш» → sh при обратной записи, и так далее.
_PAIRS = (("dj", "j"), ("dzh", "j"), ("zh", "j"), ("sh", "s"), ("ch", "c"),
          ("kh", "h"), ("ts", "c"), ("y", "i"), ("q", "k"), ("x", "ks"),
          ("w", "v"))

_HAS_CYR = re.compile(r"[а-яё]")
_CYR_WORD = re.compile(r"[А-Яа-яЁё]+")
# Латинское слово источника. Турецкие и азербайджанские буквы входят в диапазон
# через NFKD, кроме ı — она разбирается отдельно.
_LAT_WORD = re.compile(r"[^\W\d_]{4,}", re.UNICODE)

MIN_LEN = 4        # короче — скелеты слишком часто совпадают случайно
RATIO = 0.85       # ниже — уже разные слова: «контентжант» против kontenjan даёт 0.90


def skeleton(word: str) -> str:
    """Слово любой из двух письменностей → сравнимый скелет."""
    w = word.lower()
    if _HAS_CYR.search(w):
        w = "".join(_CYR.get(c, c) for c in w)
    else:
        w = w.replace("ı", "i")
        w = "".join(c for c in unicodedata.normalize("NFKD", w)
                    if not unicodedata.combining(c))
    for a, b in _PAIRS:
        w = w.replace(a, b)
    return re.sub(r"(.)\1+", r"\1", w)


def _source_index(source: str) -> dict:
    """Скелеты СТРОЧНЫХ латинских слов источника → само слово.

    Строчных — потому что спор идёт про нарицательные. Имя собственное
    кириллицей писать можно и нужно («Бакан Байрактар»), и в источнике оно
    стоит с большой буквы; аббревиатуры вроде MEB — тем более.
    """
    index = {}
    for m in _LAT_WORD.finditer(source):
        w = m.group(0)
        if w[0].islower() and not _HAS_CYR.search(w.lower()):
            index.setdefault(skeleton(w), w)
    return index


def copied_words(text: str, source: str) -> list:
    """[(слово пересказа, слово источника)] — переписанное вместо перевода."""
    index = _source_index(source)
    if not index:
        return []
    hits = []
    for w in _CYR_WORD.findall(text):
        if w[0].isupper() or len(w) < MIN_LEN:
            continue
        if zipf_frequency(w, "ru") > 0:
            continue
        s = skeleton(w)
        src = index.get(s)
        if src is None:
            # Пересказ склоняет слово, источник — своё: точного совпадения нет,
            # но и разными словами они от этого не становятся.
            src = next((o for k, o in index.items()
                        if k[0] == s[0] and abs(len(k) - len(s)) <= 3
                        and difflib.SequenceMatcher(None, s, k).ratio() >= RATIO),
                       None)
        if src is not None:
            hits.append((w, src))
    return hits


def _selfcheck():
    src = ("Enerji Bakanligi TENMAK burs programinda kontenjani 300 den 500 e "
           "cikardi. Universite ogrencileri icin basvurular eylulde. "
           "Okullarda guvenlik gorevlisi calisacak.")

    # Ради чего сторож и написан.
    assert copied_words("Увеличен контэнджан программы TENMAK.", src) == [("контэнджан", "kontenjani")]
    # Та же ошибка в другом написании — днём раньше было именно так.
    assert copied_words("Увеличен контентжант программы.", src)
    # Перевод претензий не вызывает.
    assert copied_words("Увеличена квота стипендиальной программы.", src) == []
    # Заимствование, которое уже стало русским словом, — не транслитерация,
    # даже когда стоит в источнике тем же корнем.
    assert copied_words("Университет объявил приём.", src) == []
    assert copied_words("В Анкаре прошёл хакатон.", "Ankarada hackathon duzenlendi.") == []
    # Имя собственное кириллицей — законно, спор только про нарицательные.
    assert copied_words("Выступил Байрактар.", "Bakan Bayraktar konustu.") == []
    # Без латинского источника сторож молчит, а не гадает.
    assert copied_words("Увеличен контэнджан.", "Увеличена квота приёма.") == []

    assert skeleton("kontenjan") == skeleton("контэнджан")
    # Гласные при переписывании гуляют (ö → «ё», e → «э»), поэтому точного
    # совпадения скелетов мало и рядом стоит нестрогое сравнение.
    assert skeleton("görevlisi") != skeleton("гёревлиси")
    assert copied_words("Охрану несёт гёревлиси.", src) == [("гёревлиси", "gorevlisi")]

    print("translit_guard selfcheck ok")


if __name__ == "__main__":
    _selfcheck()
